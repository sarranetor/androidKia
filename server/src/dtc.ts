export type DtcInfo = { descrizione: string | null; categoria: string };

/** Descrizione nota (se c'è) e categoria dedotta dal codice. */
export function describeCode(code: string): DtcInfo {
  const c = code.toUpperCase();
  const known = KNOWN[c] ?? null;
  const system = SYSTEM[c[0]] ?? "sconosciuto";
  let categoria = `Sistema: ${system}.`;
  if (c[0] === "P") {
    const kind = c[1] === "0" || c[1] === "2" ? "codice generico (standard SAE)" : c[1] === "1" ? "codice specifico del costruttore (Kia/Hyundai)" : "codice generico/specifico";
    categoria += ` ${kind[0].toUpperCase()}${kind.slice(1)}; area: ${P_SUBSYSTEM[c[2]] ?? "non classificata"}.`;
  } else if (c[1] === "1") {
    categoria += " Codice specifico del costruttore.";
  }
  return { descrizione: known, categoria };
}
